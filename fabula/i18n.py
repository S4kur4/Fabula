def normalize_locale(value: object) -> str:
    locale = str(value or "").strip()
    return locale if locale in SUPPORTED_LOCALES else DEFAULT_LOCALE


def get_locale() -> str:
    if not has_request_context():
        return DEFAULT_LOCALE
    user = getattr(g, "user", None)
    if user is not None and "locale" in user.keys():
        return normalize_locale(user["locale"])
    return normalize_locale(session.get("locale"))


def translate(message: str, **values: object) -> str:
    translated = ENGLISH_TRANSLATIONS.get(message, message) if get_locale() == "en" else message
    return translated.format(**values) if values else translated


def client_catalog() -> dict[str, str]:
    return ENGLISH_TRANSLATIONS if get_locale() == "en" else {}


def init_app(app) -> None:
    @app.context_processor
    def inject_i18n_context():
        locale = get_locale()
        return {
            "t": translate,
            "current_locale": locale,
            "client_i18n": client_catalog(),
            "locale_switch_label": "English" if locale == "zh-CN" else "中文",
            "locale_switch_target": "en" if locale == "zh-CN" else "zh-CN",
        }
